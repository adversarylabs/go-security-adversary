package main

import (
	"archive/zip"
	"io"
	"os"
	"path/filepath"
)

func extract(dest, archive string) error {
	r, err := zip.OpenReader(archive)
	if err != nil {
		return err
	}
	defer r.Close()
	for _, f := range r.File {
		// Vulnerable: entry.Name joined without confinement
		target := filepath.Join(dest, f.Name)
		out, err := os.Create(target)
		if err != nil {
			return err
		}
		rc, err := f.Open()
		if err != nil {
			out.Close()
			return err
		}
		_, err = io.Copy(out, rc)
		rc.Close()
		out.Close()
		if err != nil {
			return err
		}
	}
	return nil
}
